async function main() {
  console.log(`\n🌱  Seeding ${TECH_JOBS.length} Egyptian tech jobs into Supabase...\n`);

  const { error } = await supabase
    .from('jobs')
    .upsert(TECH_JOBS, { onConflict: 'id', ignoreDuplicates: false });

  if (error) {
    console.error('❌  Upsert failed:', error.message);
    process.exit(1);
  }

  console.log(`✅  Successfully seeded ${TECH_JOBS.length} jobs!`);
  console.log('  Companies:', [...new Set(TECH_JOBS.map(j => j.company))].join(', '));
  console.log('  Roles: Data Analyst, Data Engineer, ML Engineer, Software Engineer, DevOps\n');
}

main().catch(e => { console.error(e); process.exit(1); });
