import fs from 'fs';
import path from 'path';
import { createClient } from '@supabase/supabase-js';
import crypto from 'crypto';

function getEnvVal(key) {
  if (process.env[key]) return process.env[key];
  try {
    const envPath = path.resolve(process.cwd(), '.env.local');
    if (fs.existsSync(envPath)) {
      const content = fs.readFileSync(envPath, 'utf-8');
      const m = content.match(new RegExp(`^${key}=(.*)$`, 'm'));
      if (m) return m[1].trim().replace(/^['"]|['"]$/g, '');
    }
  } catch {}
  return '';
}

const SUPABASE_URL = getEnvVal('NEXT_PUBLIC_SUPABASE_URL');
const SERVICE_KEY = getEnvVal('SUPABASE_SERVICE_ROLE_KEY') || getEnvVal('NEXT_PUBLIC_SUPABASE_ANON_KEY');
const supabase = createClient(SUPABASE_URL, SERVICE_KEY, {
  auth: { autoRefreshToken: false, persistSession: false },
});

function genId(seed) {
  return 'seed_' + crypto.createHash('md5').update(seed).digest('hex').slice(0, 16);
}
function daysAgo(n) {
  return new Date(Date.now() - n * 86_400_000).toISOString();
}

